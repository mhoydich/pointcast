import fs from 'node:fs';
const {chromium}=await import(process.env.PROGRESS_PLAYWRIGHT_MODULE || 'playwright-core');
const target=process.argv[2] || 'http://127.0.0.1:8798/loom-lab/progress/';
let browser;
(async()=>{
 browser=await chromium.launch({executablePath:process.env.PROGRESS_CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const out=process.argv[3] || '/tmp/loom-progress-proof';fs.mkdirSync(out,{recursive:true});
 const errors=[],writes=[];const context=await browser.newContext({viewport:{width:1440,height:1100}});
 context.on('request',r=>{if(r.method()!=='GET')writes.push(r.method()+' '+r.url());});
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
 await page.goto(target,{waitUntil:'networkidle'});
 await page.locator('#metrics .metric').nth(3).waitFor();
 if(await page.locator('#cards').isVisible())throw Error('Desktop cards should start hidden');
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Desktop body overflow');
 await page.screenshot({path:out+'/desktop.png'});
 await page.locator('#connections').screenshot({path:out+'/map.png'});
 await page.locator('[data-filter="blocked"]').click();await page.locator('#displaymode').click();
 if(await page.locator('#cards .work-card').count()!==1)throw Error('Blocked filter must show one card');
 await page.locator('#cards .work-card').focus();await page.keyboard.press('Enter');
 if(!await page.locator('#inspector').evaluate(x=>x===document.activeElement))throw Error('Keyboard selection must focus inspector');
 if(!await page.locator('#inspector').innerText().then(t=>t.includes('Loom desk edits')))throw Error('Missing next action');
 await page.locator('[data-tab="capacity"]').click();await page.evaluate(()=>scrollTo(0,0));
 if(await page.locator('#seats article').count()!==4)throw Error('Four seats expected');
 if(await page.locator('.meters strong').allTextContents().then(a=>a.some(t=>t!=='Unknown')))throw Error('Unmetered capacity must remain unknown');
 const broken=await page.locator('#seats img').evaluateAll(imgs=>imgs.filter(i=>!i.complete||i.naturalWidth!==320).map(i=>i.src));if(broken.length)throw Error('Broken portraits '+broken);
 await page.locator('#capacity').screenshot({path:out+'/capacity.png'});
 await page.locator('[data-tab="intervals"]').click();await page.evaluate(()=>scrollTo(0,0));
 if(!await page.locator('#spans .interval-row').first().innerText().then(t=>t.includes('Unavailable')))throw Error('Missing claim must not get made-up time');
 await page.locator('#intervals').screenshot({path:out+'/intervals.png'});
 const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 mobile.on('request',r=>{if(r.method()!=='GET')writes.push(r.method()+' '+r.url());});
 const phone=await mobile.newPage();phone.on('pageerror',e=>errors.push(e.message));
 await phone.goto(target,{waitUntil:'networkidle'});
 await phone.locator('#cards .work-card').first().waitFor();
 if(await phone.locator('#map').isVisible())throw Error('Phone should start with readable cards');
 if(!await phone.locator('#cards .work-card').first().innerText().then(t=>t.includes('Work-room correction')))throw Error('Phone should put blocked handoff first');
 if(await phone.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Phone body overflow');
 await phone.screenshot({path:out+'/mobile.png'});
 await phone.locator('#cards .work-card').first().tap();
 if(!await phone.locator('#inspector').innerText().then(t=>t.includes('still blocked')||t.includes('Still blocked')))throw Error('Missing blocked explanation');
 await phone.locator('[data-tab="capacity"]').tap();
 if(await phone.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Phone capacity overflow');
 if(errors.length||writes.length)throw Error(JSON.stringify({errors,writes}));
 fs.writeFileSync(out+'/checks.json',JSON.stringify({desktop:[1440,1100],mobile:[390,844],scriptErrors:errors,nonGetRequests:writes,checks:['desktop map / phone cards','blocked filter','keyboard focus into inspector','four whole portraits loaded','unknown capacity retained','missing claim interval unavailable','no page overflow','read-only requests']},null,2));
 console.log('Local Chromium checks passed; two viewport and three panel previews saved.');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(async()=>{await browser?.close();});
