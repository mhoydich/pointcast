import fs from 'node:fs';
const {chromium}=await import(process.env.PROGRESS_PLAYWRIGHT_MODULE || 'playwright-core');
const target=process.argv[2] || 'http://127.0.0.1:8798/loom-lab/progress/';
let browser;
(async()=>{
 const executablePath=process.env.PROGRESS_CHROMIUM_PATH || (fs.existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined);
 browser=await chromium.launch({executablePath,headless:true,args:['--no-sandbox']});
 // Every non-GET is recorded and stubbed so a stray write can never leave the machine.
 const stub=ctx=>ctx.route('**/*',r=>{if(r.request().method()!=='GET'){writes.push(r.request().method()+' '+r.request().url());return r.fulfill({status:204,body:''});}return r.continue();});
 const out=process.argv[3] || '/tmp/loom-progress-proof';fs.mkdirSync(out,{recursive:true});
 const errors=[],writes=[];const context=await browser.newContext({viewport:{width:1440,height:1100}});
 await stub(context);
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
 await page.goto(target,{waitUntil:'networkidle'});
 await page.locator('#metrics .metric').nth(3).waitFor();
 if(await page.locator('#cards').isVisible())throw Error('Desktop cards should start hidden');
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Desktop body overflow');
 await page.screenshot({path:out+'/desktop.png'});
 await page.locator('#connections').screenshot({path:out+'/map.png'});
 await page.locator('[data-filter="blocked"]').click();await page.locator('#displaymode').click();
 if(await page.locator('#cards .work-card').count()!==1)throw Error('Blocked filter must show one card');
 await page.locator('#cards .work-card').focus();await page.keyboard.press('Enter');
 if(!await page.locator('#inspector').evaluate(x=>x===document.activeElement))throw Error('Keyboard selection must focus inspector');
 if(!await page.locator('#inspector').innerText().then(t=>t.includes('Loom desk edits')))throw Error('Missing next action');
 await page.locator('[data-tab="capacity"]').click();await page.evaluate(()=>scrollTo(0,0));
 if(await page.locator('#seats article').count()!==4)throw Error('Four seats expected');
 if(await page.locator('.meters strong').allTextContents().then(a=>a.some(t=>t!=='Unknown')))throw Error('Unmetered capacity must remain unknown');
 const broken=await page.locator('#seats img').evaluateAll(imgs=>imgs.filter(i=>!i.complete||i.naturalWidth!==320).map(i=>i.src));if(broken.length)throw Error('Broken portraits '+broken);
 await page.locator('#capacity').screenshot({path:out+'/capacity.png'});
 await page.locator('[data-tab="intervals"]').click();await page.evaluate(()=>scrollTo(0,0));
 const morning=page.locator('#spans .g-row[data-job="morning"]');
 if(await morning.locator('.g-bar').count()||!await morning.locator('.g-dot').count()||!await morning.innerText().then(t=>t.includes('Unavailable')))throw Error('Missing claim must show a dot and Unavailable, never a bar');
 if(await page.locator('#spans .g-row[data-job="workfix"] .g-bar.blocked').count()!==1)throw Error('Blocked item must use the blocked bar style');
 if(!await page.locator('#spans .g-nowflag').isVisible())throw Error('Now line missing');
 await page.locator('#g-states button',{hasText:'Blocked'}).click();if(await page.locator('#spans .g-row').count()!==1)throw Error('Gantt blocked filter must show one row');
 await page.locator('#g-states button',{hasText:'All'}).click();
 await page.locator('#spans .g-row').first().focus();if(!await page.locator('#g-tip').isVisible())throw Error('Focused bar must show its source receipt');
 await page.keyboard.press('Enter');if(!await page.locator('#inspector').evaluate(x=>x===document.activeElement))throw Error('Gantt row must open the inspector');
 await page.locator('[data-tab="intervals"]').click();await page.evaluate(()=>scrollTo(0,0));
 await page.mouse.move(0,0);await page.locator('#intervals').screenshot({path:out+'/intervals.png'});
 const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await stub(mobile);
 const phone=await mobile.newPage();phone.on('pageerror',e=>errors.push(e.message));
 await phone.goto(target,{waitUntil:'networkidle'});
 await phone.locator('#cards .work-card').first().waitFor();
 if(await phone.locator('#map').isVisible())throw Error('Phone should start with readable cards');
 if(!await phone.locator('#cards .work-card').first().innerText().then(t=>t.includes('Work-room correction')))throw Error('Phone should put blocked handoff first');
 if(await phone.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Phone body overflow');
 await phone.screenshot({path:out+'/mobile.png'});
 await phone.locator('#cards .work-card').first().tap();
 if(!await phone.locator('#inspector').innerText().then(t=>t.includes('still blocked')||t.includes('Still blocked')))throw Error('Missing blocked explanation');
 await phone.locator('[data-tab="capacity"]').tap();
 if(await phone.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Phone capacity overflow');
 await phone.locator('[data-tab="intervals"]').tap();await phone.evaluate(()=>scrollTo(0,0));
 if(await phone.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Phone timeline overflow');
 await phone.locator('#intervals').screenshot({path:out+'/timeline-mobile.png'});
 const recovery = await mobile.newPage();
 recovery.on('pageerror', e => errors.push(e.message));
 let reads = 0, release, started;
 const pending = new Promise(resolve => { started = resolve; });
 await recovery.route('**/data.json', async route => {
   reads++;
   if (reads === 1) return route.fulfill({status:503, body:''});
   if (reads === 2) {
     const json = await (await route.fetch()).json();
     // Fail during rendering to ensure a retry cannot duplicate cards or controls.
     json.evidence.seats = null;
     return route.fulfill({json});
   }
   await new Promise(resolve => { release = resolve; started(); });
   return route.fallback();
 });
 await recovery.goto(target);
 const retry = recovery.getByRole('button',{name:'Retry',exact:true});
 await retry.waitFor();
 if (await recovery.locator('.tabs').isVisible()) throw Error('Unloaded views must stay hidden');
 await recovery.screenshot({path:out+'/retry-mobile.png'});
 await retry.focus();
 await recovery.keyboard.press('Enter');
 await recovery.waitForFunction(()=>document.querySelector('#retry').getAttribute('aria-disabled') === null);
 if (!await retry.isVisible() || await recovery.locator('.tabs').isVisible()) throw Error('Repeat failure must keep Retry available');
 await recovery.keyboard.press('Enter');
 await pending;
 await recovery.locator('#retry[aria-disabled="true"]').waitFor();
 await recovery.keyboard.press('Enter');
 if (reads !== 3) throw Error('A pending retry must not start a second read');
 release();
 await recovery.locator('#cards .work-card').first().waitFor();
 const activeTab = recovery.locator('[data-tab="connections"]');
 if (!await activeTab.evaluate(b=>b===document.activeElement)) throw Error('Successful keyboard retry must focus the first view');
 if (await retry.isVisible() || await recovery.locator('#metrics .metric').count() !== 4) throw Error('Expected exactly one recovered dashboard');
 await recovery.keyboard.press('Tab');
 await recovery.keyboard.press('Enter');
 if (!await recovery.locator('#intervals').isVisible()) throw Error('Timeline must open after recovery');
 await recovery.keyboard.press('Tab');
 await recovery.keyboard.press('Space');
 if (!await recovery.locator('#capacity').isVisible() || await recovery.locator('#seats article').count() !== 4) throw Error('Capacity must work after recovery');
 if (reads !== 3) throw Error('Changing views must not refetch');
 await recovery.close();
 const dark=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,colorScheme:'dark'});await stub(dark);
 const night=await dark.newPage();night.on('pageerror',e=>errors.push(e.message));await night.goto(target,{waitUntil:'networkidle'});
 await night.locator('[data-tab="intervals"]').tap();await night.locator('#spans .g-row').first().waitFor();
 if(await night.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Dark phone timeline overflow');
 if(await night.evaluate(()=>getComputedStyle(document.body).backgroundColor)!=='rgb(0, 0, 0)')throw Error('Dark scheme not applied');
 await night.locator('#intervals').screenshot({path:out+'/timeline-mobile-dark.png'});
 if(errors.length||writes.length)throw Error(JSON.stringify({errors,writes}));
 fs.writeFileSync(out+'/checks.json',JSON.stringify({desktop:[1440,1100],mobile:[390,844],mobileDark:[390,844],scriptErrors:errors,nonGetRequests:writes,checks:['desktop map / phone cards','blocked filter','keyboard focus into inspector','four whole portraits loaded','unknown capacity retained','missing claim: dot and unavailable, no bar','blocked bar style and now line','gantt state filter','focused bar shows source receipt','gantt row opens inspector','phone timeline light and dark without page overflow','no page overflow','read-only requests, non-GET stubbed','snapshot failure and keyboard retry','no overlapping retry or duplicate dashboard','tabs work after recovery']},null,2));
 console.log('Local Chromium checks passed, including phone retry, recovery and keyboard navigation.');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(async()=>{await browser?.close();});
