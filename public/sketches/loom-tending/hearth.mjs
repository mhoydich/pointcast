// Static 360 × 260 pixel scene. The six wood billets and flame height reflect the log count.
export function drawHearth(canvas, logs, { unavailable = false } = {}) {
  canvas.width = 360;
  canvas.height = 260;
  const ctx = canvas.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  const count = Array.isArray(logs) ? logs.length : Number(logs);
  const level = unavailable || !Number.isFinite(count) ? 0 : Math.max(0, Math.min(6, Math.floor(count)));
  const rect = (x, y, w, h, color) => {
    ctx.fillStyle = color;
    ctx.fillRect(x, y, w, h);
  };

  // Fill one scan line at a time for a stepped contour, including diagonal ridges.
  function polygon(points, color) {
    ctx.fillStyle = color;
    const ys = points.map((p) => p[1]);
    for (let y = Math.floor(Math.min(...ys)); y < Math.ceil(Math.max(...ys)); y++) {
      const cuts = [];
      for (let i = 0; i < points.length; i++) {
        const [x1, y1] = points[i], [x2, y2] = points[(i + 1) % points.length];
        if ((y1 > y + .5) === (y2 > y + .5)) continue;
        cuts.push(x1 + (y + .5 - y1) * (x2 - x1) / (y2 - y1));
      }
      cuts.sort((a, b) => a - b);
      for (let i = 0; i + 1 < cuts.length; i += 2) {
        const left = Math.round(cuts[i]);
        ctx.fillRect(left, y, Math.round(cuts[i + 1]) - left, 1);
      }
    }
  }

  const sky = ['#151b36', '#202541', '#2e2d4d', '#423751', '#584051', '#724954', '#89575b'];
  for (let band = 0; band < sky.length; band++) {
    const top = [0, 31, 53, 72, 88, 101, 112][band];
    const bottom = [31, 53, 72, 88, 101, 112, 123][band];
    rect(0, top, 360, bottom - top, sky[band]);
    if (band) {
      for (let x = (band % 2) * 2; x < 360; x += 4) rect(x, top, 2, 1, sky[band - 1]);
    }
  }
  const stars = [[13,10],[23,45],[42,24],[51,7],[66,33],[71,17],[87,46],[96,12],[107,29],[118,60],[132,18],[148,36],[162,9],[175,55],[185,25],[202,16],[214,44],[231,7],[246,24],[264,61],[292,10],[311,50],[322,23],[342,46],[353,7],[14,70],[71,60],[127,45],[211,66]];
  for (const [x,y] of stars) {
    rect(x, y, 1 + (x % 3 === 0 ? 1 : 0), 1, x % 2 ? '#c6b5a7' : '#898ca0');
  }
  for (const [x,y] of [[89,23],[227,35],[330,13]]) {
    rect(x - 2,y,5,1,'#b4abab'); rect(x,y - 2,1,5,'#b4abab'); rect(x,y,1,1,'#fae2bd');
  }
  // Waning crescent over the water.
  polygon([[266,23],[274,19],[281,19],[275,24],[272,31],[272,37],[275,43],[283,48],[276,48],[268,44],[264,38],[263,30]], '#d9bd9e');
  polygon([[267,26],[273,22],[276,21],[272,27],[270,34],[271,39],[274,44],[268,40],[265,34]], '#f8dec0');
  polygon([[22,65],[41,65],[44,62],[56,62],[59,60],[69,60],[74,63],[88,63],[92,65],[104,65],[106,67],[18,67]], '#483b54');
  polygon([[202,81],[216,80],[221,78],[239,78],[245,74],[254,74],[258,76],[274,76],[278,79],[294,80],[301,82],[201,83]], '#664952');
  rect(32,71,31,1,'#5c4656'); rect(234,84,41,1,'#80535a');
  rect(0,122,360,45,'#40415b');
  rect(0,123,360,1,'#b27b70'); rect(0,126,360,2,'#615163');
  // Broken reflections, with the brightest water beneath the moon.
  for (let line = 0; line < 9; line++) {
    const y = 130 + line * 4;
    const half = 7 + line * 2;
    rect(274 - half + (line % 3) * 4, y, half + 5, 1, '#95716e');
    rect(280 + (line % 3) * 3, y + 1, half - 5, 1, '#7a616c');
    for (let x = (line * 31) % 53; x < 360; x += 53 + line) {
      rect(x,y + 2,6 + x % 11,1,line % 2 ? '#5e5367' : '#585165');
    }
  }
  // Distant islands, promontories and nearer shale ledges.
  polygon([[0,100],[15,101],[25,105],[45,107],[55,113],[76,114],[93,120],[111,122],[126,126],[0,126]], '#393548');
  polygon([[212,123],[226,120],[237,119],[247,116],[256,118],[264,119],[279,124]], '#534656');
  polygon([[0,111],[18,115],[32,125],[52,127],[67,136],[81,139],[89,145],[112,148],[105,154],[0,164]], '#282a41');
  polygon([[360,94],[348,98],[340,107],[323,111],[314,119],[301,122],[295,128],[279,132],[277,136],[317,137],[360,128]], '#333047');
  polygon([[360,127],[352,127],[343,134],[325,138],[313,145],[295,147],[286,152],[269,156],[251,162],[250,168],[360,175]], '#26283d');
  rect(10,146,34,1,'#554854'); rect(55,151,20,1,'#504352');
  rect(308,149,17,1,'#5b4a59'); rect(333,140,13,1,'#544855');
  polygon([[0,154],[36,156],[55,161],[93,163],[124,168],[170,169],[197,167],[237,168],[288,160],[329,159],[360,153],[360,260],[0,260]], '#292939');
  polygon([[0,173],[44,170],[77,175],[119,172],[157,174],[184,173],[231,170],[270,173],[314,167],[360,170],[360,260],[0,260]], '#34303d');
  polygon([[0,203],[25,206],[59,202],[98,205],[117,211],[165,207],[192,213],[244,208],[286,210],[318,204],[360,207],[360,260],[0,260]], '#2b2936');
  for (let i = 0; i < 140; i++) {
    const x = (i * 47 + (i % 7) * 19) % 360, y = 178 + ((i * 17 + i % 4) % 80);
    rect(x,y,1 + i % 4,1,i % 4 === 0 ? '#51414a' : '#3e3542');
  }
  for (const [x,y,w] of [[14,191,29],[49,227,22],[77,183,13],[261,204,19],[282,237,33],[332,189,19]]) {
    polygon([[x-w/2,y+2],[x-w/4,y-3],[x+w/5,y-4],[x+w/2,y+1],[x+w/3,y+3]], '#202333');
    rect(x-w/4|0, y-3, w/3|0,1,'#625262');
  }
  // Three broad steps of reflected firelight on the sand.
  if (level) {
    for (const [spread, y, color] of [[70,217,'#42343b'],[52,214,'#503b3c'],[29,213,'#5e4140']]) {
      const w = spread * (.55 + .075 * level);
      polygon([[178-w,y-3],[185-w/2,y-6],[179+w*.7,y-5],[184+w,y],[176+w*.7,y+4],[176-w*.6,y+5],[174-w,y+2]],color);
    }
  }
  // Fold-out steel legs and shadow, viewed from a low angle.
  polygon([[125,219],[146,214],[206,215],[234,219],[218,223],[142,223]], '#23232e');
  polygon([[147,186],[156,187],[149,217],[144,218]], '#171c28');
  polygon([[204,187],[212,185],[218,215],[213,217]], '#171c28');
  polygon([[151,191],[154,191],[148,215],[146,216]], '#686069');
  polygon([[208,188],[211,187],[216,212],[214,213]], '#72606a');
  rect(163,201,39,3,'#242633');
  polygon([[123,174],[135,166],[222,166],[238,175],[233,182],[127,183]], '#84808a');
  polygon([[128,174],[139,168],[220,168],[232,174],[226,179],[138,180]], '#282832');
  // Weathered coals catch light even after the last full flame dies down.
  for (let i=0; i<19; i++) {
    const x = 136 + ((i * 19) % 86), y = 170 + (i * 3) % 7;
    rect(x,y,3+i%5,2,unavailable ? '#55505b' : (i%4 ? '#8b4d42' : '#f0a367'));
  }

  // Each additional log adds a distinct billet, with a cut face and dark bark.
  const billets = [[143,169,181,178],[184,175,218,164],[147,176,191,164],[176,166,214,176],[158,162,197,169],[165,173,205,160]];
  for (const [x,y,x2,y2] of billets.slice(0, level)) {
    polygon([[x,y-4],[x2,y2-4],[x2+2,y2-1],[x2,y2+4],[x,y+4],[x-2,y+1]],'#543636');
    polygon([[x,y-4],[x2,y2-4],[x2-2,y2-2],[x,y-1]],'#d18a60');
    polygon([[x-2,y-2],[x+1,y-4],[x+4,y-2],[x+4,y+1],[x+1,y+4],[x-2,y+2]],'#ecac70');
    rect(x,y,2,2,'#956048');
  }
  if (level) {
    const size = [0, .29, .44, .61, .74, .89, 1][level];
    const flame = (points, color) => polygon(points.map(([x,y]) => [180 + x*size, 173 + y*size]), color);
    flame([[-42,-1],[-47,-11],[-46,-24],[-40,-18],[-40,-34],[-45,-49],[-36,-43],[-25,-27],[-22,-45],[-15,-62],[-16,-78],[-27,-91],[-13,-88],[-1,-77],[4,-61],[8,-72],[8,-89],[18,-99],[22,-114],[28,-101],[26,-85],[19,-74],[19,-61],[29,-70],[33,-84],[40,-70],[39,-57],[31,-42],[39,-45],[44,-52],[46,-33],[40,-20],[47,-24],[44,-11],[34,-2],[20,2],[-20,3]],'#e76240');
    flame([[-32,-3],[-36,-18],[-28,-12],[-28,-31],[-30,-38],[-20,-28],[-16,-21],[-13,-41],[-7,-53],[-8,-69],[-12,-78],[-2,-66],[3,-47],[10,-48],[13,-61],[26,-79],[29,-83],[27,-67],[20,-53],[20,-37],[27,-42],[35,-53],[34,-37],[29,-25],[37,-29],[34,-13],[24,-2],[7,2],[-12,3]],'#ff943f');
    flame([[-18,0],[-24,-11],[-21,-23],[-16,-17],[-14,-11],[-12,-25],[-4,-37],[-3,-47],[2,-39],[5,-25],[12,-32],[16,-43],[17,-30],[12,-19],[18,-22],[23,-29],[21,-15],[26,-18],[23,-7],[14,0]],'#ffd265');
    flame([[-8,-1],[-11,-10],[-6,-8],[-3,-16],[2,-22],[2,-13],[7,-15],[9,-19],[11,-10],[7,-3],[3,0]],'#fff2ae');
    for(const [x,y,w] of [[-45,-67,3],[-24,-107,2],[32,-122,2],[49,-89,3],[-34,-121,1],[55,-109,1]].slice(0,level)){
      rect(Math.round(180+x*size),Math.round(173+y*size),w,w+1,'#f1a267');
    }
  }

  // The enamel lip and folded front face sit in front of the combustibles.
  polygon([[122,175],[236,175],[233,182],[220,192],[214,198],[144,198],[128,184]],'#282a35');
  polygon([[128,181],[231,181],[217,193],[144,194]],'#45404a');
  polygon([[136,184],[220,184],[211,190],[146,191]],level ? '#685054' : '#504a54');
  polygon([[122,175],[236,175],[233,179],[126,180]],level ? '#cf927b' : '#8f8990');
  rect(133,176,75,1,level ? '#ffd09c' : '#b2a6a2');
  for (let x = 151; x < 215; x += 9) {
    rect(x,185,4,3,'#252330');
    if(level > 1) rect(x,187,3,1,'#ab6350');
  }
  rect(138,182,2,2,'#ab9591'); rect(218,182,2,2,'#ab9591');
}
