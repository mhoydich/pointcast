#!/usr/bin/env node
/**
 * Regenerates src/lib/loom/noun-data.mjs: the small slice of the official Nouns
 * trait data (CC0) that the Loom share card needs. Run: node scripts/build-loom-noun-data.mjs
 * Source: public/images/nouns-money/source-100/sources/official-image-data.json
 * (nouns-monorepo packages/nouns-assets image-data.json). Includes the 7 room
 * recipes plus a fixed pool of 16 evenly spaced parts per kind for address-picked Nouns.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('../public/images/nouns-money/source-100/sources/official-image-data.json', import.meta.url), 'utf8'));
const KINDS = { body: 'bodies', accessory: 'accessories', head: 'heads', glasses: 'glasses' };
const RECIPES = [
  ['body-teal-light', 'accessory-glasses-logo', 'head-calendar', 'glasses-square-black'],
  ['body-bluegrey', 'accessory-tie-red', 'head-chart-bars', 'glasses-square-red'],
  ['body-gold', 'accessory-sunset', 'head-watch', 'glasses-square-yellow-saturated'],
  ['body-green', 'accessory-pocket-pencil', 'head-stapler', 'glasses-square-teal'],
  ['body-grayscale-1', 'accessory-tie-black-on-white', 'head-pencil-tip', 'glasses-square-fullblack'],
  ['body-computerblue', 'accessory-id', 'head-mailbox', 'glasses-square-blue'],
  ['body-orange', 'accessory-stripes-blit', 'head-basketball', 'glasses-square-black'],
];
const parts = {}, pool = {};
for (const [kind, key] of Object.entries(KINDS)) {
  const list = src.images[key];
  parts[kind] = {}; pool[kind] = [];
  for (let i = 0; i < 16; i += 1) pool[kind].push(list[Math.floor((i * list.length) / 16)].filename);
  const names = new Set(pool[kind]);
  RECIPES.forEach((r) => names.add(r[Object.keys(KINDS).indexOf(kind)]));
  for (const n of [...names].sort()) {
    const p = list.find((x) => x.filename === n);
    if (!p) throw new Error(`missing official trait ${n}`);
    parts[kind][n] = p.data.replace(/^0x/, '');
  }
}
const out = `// GENERATED by scripts/build-loom-noun-data.mjs from the official Nouns image data (CC0). Do not edit.
export const NOUN_PALETTE = ${JSON.stringify(src.palette)};
export const NOUN_BACKGROUNDS = ${JSON.stringify({ cool: src.bgcolors[0], warm: src.bgcolors[1] })};
export const NOUN_PARTS = ${JSON.stringify(parts)};
export const NOUN_POOL = ${JSON.stringify(pool)};
`;
writeFileSync(new URL('../src/lib/loom/noun-data.mjs', import.meta.url), out);
console.log('wrote', out.length, 'bytes');
