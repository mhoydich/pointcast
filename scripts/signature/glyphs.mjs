/**
 * PointCast Script, the house signature hand.
 *
 * Each letter is a list of pen strokes: points the nib passes through, and a
 * width. `scripts/signature/build-font.mjs` turns these into a TTF and into
 * the path JSON the studio draws. To add a character, add a key here (the
 * character itself, or a name plus `unicode`) and run the build script.
 * Coordinates are upright font units, y up. The build applies SLANT.
 *
 * Nothing here is traced from another font.
 */

