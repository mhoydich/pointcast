function fill(html, s) {
  const parts = { 'CHROME:HEAD': head(s), 'CHROME:TOP': top(s), 'CHROME:PLAIN': plain(s), 'CHROME:LICENCE': licence(s), 'CHROME:FOOTER': footer(s) };
  for (const [k, v] of Object.entries(parts)) {
    const marker = `<!--${k}-->`;
    if (html.split(marker).length !== 2) throw new Error(`${s.slug}: expected exactly one ${marker}`);
    html = html.replace(marker, () => v);
  }
  if (html.split('/*CHROME:CSS*/').length !== 2) throw new Error(`${s.slug}: expected one CSS marker`);
  return html.replace('/*CHROME:CSS*/', () => CSS);
}

function buildSurf(s) {
  const S = new Map(surf.SOURCES.map(([k, label, title, u, o]) => [k, { label, title, url: u, read: !(o && o.read === false) }]));
  const order = [];
  const expand = (_, keys) => {
    const out = keys.split(',').map((raw) => {
      const k = raw.trim();
      const e = S.get(k);
      if (!e) throw new Error(`surf house: missing source ${k}`);
      if (!order.includes(k)) order.push(k);
      return `<a class="src" href="${esc(e.url)}" target="_blank" rel="noopener" title="${esc(e.title)}">${esc(e.label)}</a>`;
    });
    return `<span class="srcs">${out.join(' ')}</span>`;
  };
  const t = readFileSync(join(here, 'surf-house.src.html'), 'utf8');
  const [bodyRaw, tailRaw] = t.split('<!--SOURCES-->');
  if (tailRaw === undefined) throw new Error('surf house: no <!--SOURCES--> marker');
  const body = bodyRaw.replace(/\{\{s:([^}]+)\}\}/g, expand);
  const tail = tailRaw.replace(/\{\{s:([^}]+)\}\}/g, expand);
  const unused = [...S.keys()].filter((k) => !order.includes(k));
  if (unused.length) throw new Error(`surf house: sources never cited: ${unused.join(', ')}`);
  const lis = order.map((k) => {
    const e = S.get(k);
    const host = e.url.replace(/^https?:\/\/(www\.)?([^/:]+).*/, '$2');
    return `<li><a href="${esc(e.url)}" target="_blank" rel="noopener">${esc(e.title)}</a><span class="host">${esc(host)}</span></li>`;
  });
  const html = `${body}<ol class="sources">\n${lis.join('\n')}\n</ol>${tail}`.replace('%%NSRC%%', String(S.size));
  const sources = order.map((k) => { const e = S.get(k); return { title: e.title, url: e.url, opened: surf.OPENED, read: e.read }; });
  return { html: fill(html, s), sources };
}

function buildMilk(s) {
  const t = readFileSync(join(here, 'fresh-milk.src.html'), 'utf8');
  if (t.split('/*SRC_JSON*/[]').length !== 2) throw new Error('fresh milk: no source marker');
  const rows = milk.SOURCES.map(([title, u]) => [title, u]);
  const html = t.replace('/*SRC_JSON*/[]', () => JSON.stringify(rows).replace(/</g, '\\u003c'));
  // Every sourced link in the page must be in the list, and the other way round.
  const inPage = new Set([...t.matchAll(/https:\/\/[^"'\s<>]+/g)].map((m) => m[0].replace(/&amp;/g, '&')));
  for (const [, u] of milk.SOURCES) if (!inPage.has(u)) throw new Error(`fresh milk: source not linked beside a claim: ${u}`);
  const listed = new Set(milk.SOURCES.map((r) => r[1]));
  for (const u of inPage) if (!listed.has(u)) throw new Error(`fresh milk: link not in the source list: ${u}`);
  const sources = milk.SOURCES.map(([title, u, o]) => ({ title, url: u, opened: milk.OPENED, read: !(o && o.read === false), ...(o && o.partial ? { partial: true } : {}) }));
  return { html: fill(html, s), sources };
}

export function build() {
  const files = {};
  const index = [];
  for (const s of STUDIES) {
    const { html, sources } = s.file === 'surf-house' ? buildSurf(s) : buildMilk(s);
    files[`public/coast-commons/${s.slug}/index.html`] = html;
    index.push({
      slug: s.slug, title: s.title, url: url(s), summary: s.summary, verified: READ_ON, sections: s.sections,
      not_verified: s.not_verified,
      source_count: sources.length, sources_read: sources.filter((x) => x.read).length,
      sources_at: `${url(s)}#${s.slug === 'sb-surf-house' ? 'sources' : 'h-src'}`,
    });
  }
  return { files, index };
}

// For the hub and /coast-commons.json. Source lists stay on the pages themselves, beside each claim.
export function studiesIndex() {
  return {
    block: `${SITE}/b/${BLOCK}`,
    author: "Claude, at Mike Hoydich's request",
    notice: NOTICE,
    method: `Every source was opened on ${READ_ON} and is linked beside the claim it supports. Paraphrase only. No private individuals are named, and a business is named only where the page links its own site or an official page. What could not be verified is listed here and repeated on the page beside the claim it affects.`,
    licence: { status: 'chosen', chosen: '2026-11-12', spdx: 'CC-BY-4.0', covers: 'the words and drawings of the two study pages; not the linked sources', note: 'https://pointcast.xyz/coast-commons/LICENSE.txt' },
    list: build().index,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { files } = build();
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [rel, text] of Object.entries(files)) {
    const abs = join(root, rel);
    if (check) {
      let cur = null;
      try { cur = readFileSync(abs, 'utf8'); } catch {}
      if (cur !== text) { stale += 1; console.error(`stale: ${rel}`); }
    } else {
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, text);
      console.log(`wrote ${rel} (${text.length} bytes)`);
    }
  }
  if (check) {
    if (stale) { console.error('Run: node scripts/coast-commons-studies/build.mjs'); process.exit(1); }
    console.log(`coast-commons-studies: ${Object.keys(files).length} files match`);
  }
}
