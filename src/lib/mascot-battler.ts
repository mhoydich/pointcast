export const MASCOT_CARDS = profiles.map((profile) => {
  const team = teamBySlug.get(profile.slug);
  const mascotClass = classById.get(profile.mascotClass);
  if (!team) throw new Error(`Mascot profile has no PointCast 25 team: ${profile.slug}`);
  if (!mascotClass) throw new Error(`Unknown mascot class: ${profile.mascotClass}`);

  return {
    ...profile,
    school: team.school,
    short: team.short,
    conference: team.conference,
    rank: team.rank,
    accent: team.accent,
    form: Math.max(46, 96 - team.rank * 2),
    pointcastReason: team.reason,
    pointcastProof: team.proof,
    art: mascotClass.art,
    className: mascotClass.name,
    classFieldName: mascotClass.fieldName,
    classInstinct: mascotClass.instinct,
    sourceCheckedAt: '2026-07-27',
    canonical: `https://pointcast.xyz/mascot-battler/${profile.slug}`,
    machineEdition: `https://pointcast.xyz/mascot-battler/${profile.slug}.json`,
  };
});

