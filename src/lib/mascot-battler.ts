export const MASCOT_CONFERENCES = Array.from(new Set(MASCOT_CARDS.map((card) => card.conference)));

export function getMascotCard(slug: string) {
  return MASCOT_CARDS.find((card) => card.slug === slug);
}

export function mascotCardPower(card: MascotCard) {
  return card.locality + card.legacy + card.myth + card.balance + card.form;
}

export function mascotCardFromTeam(team: PointCast25Team) {
  return MASCOT_CARDS.find((card) => card.school === team.school);
}
