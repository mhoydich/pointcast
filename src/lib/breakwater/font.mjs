export const GLYPHS = Object.freeze(RAW);

export function glyph(ch) {
  return RAW[ch] || RAW[String(ch).toUpperCase()] || RAW['?'];
}

/** Width in logical pixels of `text` drawn at `scale` with one blank column between glyphs. */
export function textWidth(text, scale = 1, spacing = 1) {
  if (!text.length) return 0;
  return (text.length * (GLYPH_W + spacing) - spacing) * scale;
}

/**
 * Call `cb(x, y, size)` once for every lit pixel of `text` placed at (x, y).
 * `size` is `scale`, so the callback can fill one square per call.
 */
export function eachPixel(text, x, y, scale = 1, cb, spacing = 1) {
  const pitch = (GLYPH_W + spacing) * scale;
  for (let i = 0; i < text.length; i += 1) {
    const rows = glyph(text[i]);
    for (let r = 0; r < GLYPH_H; r += 1) {
      const row = rows[r];
      for (let c = 0; c < GLYPH_W; c += 1) {
        if (row[c] === '1') cb(x + i * pitch + c * scale, y + r * scale, scale);
      }
    }
  }
}

/** Every pixel of `text` as [x, y] pairs, for tests and for static art. */
export function pixelsOf(text, x = 0, y = 0, scale = 1, spacing = 1) {
  const out = [];
  eachPixel(text, x, y, scale, (px, py) => out.push([px, py]), spacing);
  return out;
}
