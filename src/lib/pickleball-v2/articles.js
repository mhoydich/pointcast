const ORIGIN = 'https://pointcast.xyz';
const itemText = (item) => typeof item === 'string' ? item : item?.text || '';

export function getArticleBySlug(slug) {
  return articles.find(article => article.slug === slug);
}

export const articleBySlug = getArticleBySlug;

/** Plain editorial copy, excluding navigation, source notes, and diagram legends. */
export function articleText(article) {
  return [article.title, article.dek, ...(article.introduction || []).map(itemText),
    ...article.sections.flatMap(section => [section.title, ...section.paragraphs.map(itemText), ...(section.list || []).map(itemText), ...(section.afterParagraphs || []).map(itemText)])].join('\n\n');
}

export function articleWordCount(article) {
  return articleText(article).trim().split(/\s+/u).filter(Boolean).length;
}

export function practiceUrl(article) {
  const goal = ['backhand', 'reset', 'doubles'].includes(article.goal) ? article.goal : 'backhand';
  return `/pickleball/home?goal=${goal}#pb-v2-planner`;
}

export function buildArticleJsonLd(article) {
  return {
    '@context': 'https://schema.org', '@type': 'Article',
    '@id': `${ORIGIN}${article.url}#article`,
    url: `${ORIGIN}${article.url}`, mainEntityOfPage: `${ORIGIN}${article.url}`,
    headline: article.title, description: article.dek,
    image: [`${ORIGIN}${article.socialImage}`],
    author: { '@type': 'Organization', name: 'PointCast Editorial', url: `${ORIGIN}/pickleball/home` },
    publisher: { '@type': 'Organization', name: 'PointCast', url: ORIGIN },
    datePublished: article.publishedAt, dateModified: article.modifiedAt,
    inLanguage: 'en-US', articleSection: 'Pickleball instruction',
    wordCount: articleWordCount(article), articleBody: articleText(article),
    citation: article.sources.map(source => source.url),
  };
}

/** JSON-safe public article; no practice state or visitor data enters this feed. */
export function publicArticle(article) {
  return {
    schemaVersion: 1, ...article, canonicalUrl: `${ORIGIN}${article.url}`,
    practiceUrl: practiceUrl(article), wordCount: articleWordCount(article),
    jsonLd: buildArticleJsonLd(article),
  };
}
